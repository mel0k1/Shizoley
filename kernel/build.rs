use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

// builds every userspace program (programs/<name>/main.cpp) with the host
// g++ against the shz runtime, packs the static elfs into a ustar archive
// the kernel embeds and walks as its initrd
fn main() {
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let usr = manifest.parent().unwrap().join("userspace");
    let inc = usr.join("include");
    let src = usr.join("src");
    let programs = usr.join("programs");

    println!("cargo:rerun-if-changed={}", src.display());
    println!("cargo:rerun-if-changed={}", programs.display());
    println!("cargo:rerun-if-changed={}", usr.join("link.ld").display());

    let cxx = env::var("CXX").unwrap_or_else(|_| "g++".into());
    let cc = env::var("CC").unwrap_or_else(|_| "gcc".into());

    // shared shz runtime objects
    let mut runtime = Vec::new();
    for (i, unit) in ["syscall.cpp", "io.cpp", "eq.cpp", "start.cpp"]
        .iter()
        .enumerate()
    {
        runtime.push(compile(
            &cxx,
            &inc,
            &src.join(unit),
            &out.join(format!("r{}.o", i)),
        ));
    }

    // one static elf per programs/<name>/main.cpp
    let mut progs: Vec<PathBuf> = fs::read_dir(&programs)
        .unwrap_or_else(|e| panic!("kernel build: cannot read programs dir: {e}"))
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter(|p| p.join("main.cpp").exists())
        .collect();
    progs.sort();

    // programs can ship a guest image (devd): guest.c compiles freestanding
    // to raw bytes pinned at its load address, a generated header feeds the
    // monitor so it copies the image into guest ram; must run before the
    // program compilation (devd/main.cpp includes the generated header)
    let guest_hdr = out.join("guest_blob.h");
    let mut guest_built = false;
    for prog in progs.iter() {
        let gsrc = prog.join("guest.c");
        if !gsrc.exists() {
            continue;
        }
        let name = prog.file_name().unwrap().to_string_lossy().to_string();
        let gobj = out.join(format!("guest_{name}.o"));
        println!("cargo:rerun-if-changed={}", gsrc.display());
        let status = Command::new(&cc)
            .args([
                "-m64",
                "-ffreestanding",
                "-fno-pic",
                "-fno-stack-protector",
                "-fno-asynchronous-unwind-tables",
                "-mno-sse",
                "-mno-sse2",
                "-mno-mmx",
                "-mno-red-zone",
                "-O2",
                "-Wall",
                "-Wextra",
                "-Werror",
                "-c",
            ])
            .arg(&gsrc)
            .arg("-o")
            .arg(&gobj)
            .status()
            .unwrap_or_else(|e| panic!("kernel build: cannot run {cc} ({e})"));
        if !status.success() {
            panic!("kernel build: guest image of '{name}' failed");
        }
        let gbin = out.join(format!("guest_{name}.bin"));
        let status = Command::new("ld")
            .args(["-m", "elf_x86_64", "-Ttext=0x9000", "--oformat", "binary"])
            .arg(&gobj)
            .arg("-o")
            .arg(&gbin)
            .status()
            .unwrap_or_else(|e| panic!("kernel build: cannot run ld ({e})"));
        if !status.success() {
            panic!("kernel build: guest binary of '{name}' failed");
        }
        let blob = fs::read(&gbin).expect("kernel build: guest binary read failed");
        let mut hdr = String::from("// generated by build.rs from guest.c — do not edit\n");
        hdr.push_str("static const unsigned char guest_blob[] = {");
        for (i, b) in blob.iter().enumerate() {
            if i % 12 == 0 {
                hdr.push_str("\n    ");
            }
            hdr.push_str(&format!("0x{:02X},", b));
        }
        hdr.push_str("\n};\n");
        fs::write(&guest_hdr, hdr).expect("kernel build: guest header write failed");
        guest_built = true;
    }
    if !guest_built {
        fs::write(&guest_hdr, "// no guest image in this build\n").unwrap();
    }

    let mut images: Vec<(String, Vec<u8>)> = Vec::new();
    for prog in &progs {
        let name = prog.file_name().unwrap().to_string_lossy().to_string();
        let main = prog.join("main.cpp");
        println!("cargo:rerun-if-changed={}", main.display());
        let obj = compile(&cxx, &inc, &main, &out.join(format!("p_{}.o", name)));
        let elf = out.join(format!("{}.elf", name));
        let status = Command::new(&cxx)
            .args(["-nostdlib", "-static", "-no-pie", "-o"])
            .arg(&elf)
            .arg(format!("-Wl,-T,{}", usr.join("link.ld").display()))
            .args(["-Wl,--build-id=none", "-Wl,-z,noexecstack"])
            .args(&runtime)
            .arg(&obj)
            .status()
            .unwrap_or_else(|e| panic!("kernel build: cannot link {name} ({e})"));
        if !status.success() {
            panic!("kernel build: link of '{name}' failed");
        }
        images.push((name, fs::read(&elf).expect("kernel build: elf read failed")));
    }

    if images.is_empty() {
        panic!("kernel build: no userspace programs found");
    }

    // plain data files from userspace/rootfs ride along as initrd entries
    let rootfs = usr.join("rootfs");
    println!("cargo:rerun-if-changed={}", rootfs.display());
    if let Ok(files) = fs::read_dir(&rootfs) {
        let mut paths: Vec<PathBuf> = files
            .filter_map(|e| e.ok())
            .map(|e| e.path())
            .filter(|p| p.is_file())
            .collect();
        paths.sort();
        for f in paths {
            let name = f.file_name().unwrap().to_string_lossy().to_string();
            images.push((
                name,
                fs::read(&f).expect("kernel build: rootfs read failed"),
            ));
        }
    }

    // ustar archive: 512-byte header + data + padding per file, zero tail
    let mut tar: Vec<u8> = Vec::new();
    for (name, data) in &images {
        tar.extend_from_slice(&tar_header(name, data.len()));
        tar.extend_from_slice(data);
        let pad = (512 - data.len() % 512) % 512;
        tar.extend(std::iter::repeat_n(0u8, pad));
    }
    tar.extend_from_slice(&[0u8; 1024]);
    fs::write(out.join("initrd.tar"), &tar).expect("kernel build: initrd write failed");
    // the kernel embeds the blob page-aligned (it maps it straight into
    // user space), so the length has to be known at compile time
    fs::write(
        out.join("initrd_len.rs"),
        format!("pub const INITRD_LEN: usize = {};\n", tar.len()),
    )
    .expect("kernel build: initrd_len write failed");
}

fn compile(cxx: &str, inc: &Path, unit: &Path, obj: &Path) -> PathBuf {
    let status = Command::new(cxx)
        .args([
            "-std=c++20",
            "-ffreestanding",
            "-fno-exceptions",
            "-fno-rtti",
            "-fno-stack-protector",
            "-fno-threadsafe-statics",
            "-fno-asynchronous-unwind-tables",
            "-fno-pie",
            "-O2",
            "-Wall",
            "-Wextra",
            "-Werror",
            "-c",
        ])
        .arg("-I")
        .arg(inc)
        .arg("-I")
        .arg(PathBuf::from(env::var("OUT_DIR").unwrap()))
        .arg(unit)
        .arg("-o")
        .arg(obj)
        .status()
        .unwrap_or_else(|e| panic!("kernel build: cannot run {cxx} ({e})"));
    if !status.success() {
        panic!("kernel build: {} failed", unit.display());
    }
    obj.to_path_buf()
}

// posix ustar header with a correct checksum so standard tools can read it too
fn tar_header(name: &str, size: usize) -> [u8; 512] {
    let mut h = [0u8; 512];
    h[..name.len()].copy_from_slice(name.as_bytes());
    h[100..107].copy_from_slice(b"0000644");
    h[108..115].copy_from_slice(b"0000000");
    h[116..123].copy_from_slice(b"0000000");
    h[124..135].copy_from_slice(format!("{:011o}", size).as_bytes());
    h[135] = 0;
    h[136..147].copy_from_slice(b"00000000000");
    h[147] = 0;
    h[148..156].copy_from_slice(b"        ");
    h[156] = b'0';
    h[257..262].copy_from_slice(b"ustar");
    h[263..265].copy_from_slice(b"00");
    let sum: u32 = h.iter().map(|&b| b as u32).sum();
    h[148..154].copy_from_slice(format!("{:06o}", sum).as_bytes());
    h[154] = 0;
    h[155] = b' ';
    h
}
